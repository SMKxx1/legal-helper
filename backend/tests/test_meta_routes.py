def test_validation_422_uses_envelope_and_never_reflects_submitted_input(client):
    # A pydantic 422 (here an over-long login password) must render the unified envelope AND must
    # NOT echo the submitted value back — FastAPI's default 422 reflects `input` verbatim, which on
    # a password field is a credential leak.
    secret = "p" * 300  # exceeds the login password max_length
    resp = client.post("/api/auth/login", json={"user_id": "x", "password": secret})
    assert resp.status_code == 422
    assert set(resp.json()) == {"error"}
    assert resp.json()["error"]["code"] == "unprocessable"
    assert secret not in resp.text
